// ═══════════════════════════════════════════════════════════════════
// 🔴 ПОСТ-ВАЛИДАЦИЯ: БЫСТРЫЙ ФИКС ДЛЯ ВНЕДРЕНИЯ СЕГОДНЯ
// ═══════════════════════════════════════════════════════════════════
// Добавь эту ноду ПОСЛЕ "Clean Markdown" и ПЕРЕД "Convert to File"
// Название ноды: "Validate & Fix Laws"

const analysis = $input.first().json.content;

// ═══════════════════════════════════════════════════════════════════
// ПРАВИЛА ВАЛИДАЦИИ (добавляй сюда новые по мере нахождения ошибок)
// ═══════════════════════════════════════════════════════════════════

const validationRules = [
  {
    name: "Статья 575 для нежилых помещений",
    pattern: /статья 575.*?ГК РК/gi,
    check: (text) => {
      // Если упоминается 575 И есть слова про нежилые помещения
      const has575 = /статья 575/gi.test(text);
      const hasNonResidential = /(нежил|офис|склад|магазин|коммерческ)/gi.test(text);
      return has575 && hasNonResidential;
    },
    error: "КРИТИЧЕСКАЯ ОШИБКА: Статья 575 применяется только к ЖИЛЫМ помещениям! Для нежилых нужна статья 556.",
    fix: (text) => {
      return text
        .replace(/статья 575 Гражданского кодекса РК \(Особенная часть\)/gi, 
                 'статья 556 Гражданского кодекса РК (Особенная часть, Глава 29)')
        .replace(/статья 575 ГК РК/gi, 'статья 556 ГК РК');
    }
  },
  
  {
    name: "Статьи 406-410 для расторжения",
    pattern: /статья 40[6-9]|статья 410/gi,
    check: (text) => {
      return /статья 40[6-9]|статья 410/gi.test(text);
    },
    error: "КРИТИЧЕСКАЯ ОШИБКА: Статьи 406-410 не существуют в контексте расторжения! Правильно: статьи 401-405.",
    fix: (text) => {
      return text
        .replace(/статьи 406-410 Гражданского кодекса РК/gi, 
                 'статьи 401-405 Гражданского кодекса РК (Общая часть, Глава 28)')
        .replace(/статья 406 ГК РК/gi, 'статья 401 ГК РК')
        .replace(/статья 408 ГК РК/gi, 'статья 403 ГК РК');
    }
  },
  
  {
    name: "Статья 380 для неустойки",
    pattern: /статья 380.*?неустойк/gi,
    check: (text) => {
      return /статья 380.*?неустойк/gi.test(text);
    },
    error: "ОШИБКА: Статья 380 — это про свободу договора, не про неустойку! Правильно: статья 350.",
    fix: (text) => {
      return text.replace(/статья 380 Гражданского кодекса РК.*?неустойк/gi, 
                          'статья 350 Гражданского кодекса РК (Общая часть) устанавливает понятие неустойк');
    }
  },
  
  {
    name: "Глава 30 для нежилых помещений",
    pattern: /Глава 30.*?нежил/gi,
    check: (text) => {
      const hasChapter30 = /Глава 30/gi.test(text);
      const hasNonResidential = /(нежил|офис|склад|магазин)/gi.test(text);
      return hasChapter30 && hasNonResidential;
    },
    error: "ОШИБКА: Глава 30 применяется только к ЖИЛЫМ помещениям! Для нежилых — Глава 29.",
    fix: (text) => {
      // Заменяем Глава 30 на Глава 29 в контексте нежилых помещений
      return text.replace(/Глава 30 "Аренда"/gi, 'Глава 29 "Аренда"');
    }
  },
  
  {
    name: "Отсутствие статьи 404",
    pattern: /односторонн.*?отказ/gi,
    check: (text) => {
      const hasUnilateralRefusal = /односторонн.*?отказ/gi.test(text);
      const has404 = /статья 404/gi.test(text);
      return hasUnilateralRefusal && !has404;
    },
    error: "ПРЕДУПРЕЖДЕНИЕ: Упомянут односторонний отказ, но не упомянута статья 404 ГК РК!",
    fix: (text) => {
      // Добавляем упоминание статьи 404
      const insertion = '\n\nСогласно статье 404 Гражданского кодекса РК (Общая часть, Глава 28), односторонний отказ от исполнения обязательства допускается в случаях, предусмотренных законодательством или договором.\n\n';
      
      // Вставляем после первого упоминания одностороннего отказа
      return text.replace(/(односторонн.*?отказ.*?\n)/, `$1${insertion}`);
    }
  }
];

// ═══════════════════════════════════════════════════════════════════
// ЛОГИКА ВАЛИДАЦИИ
// ═══════════════════════════════════════════════════════════════════

let errors = [];
let fixedText = analysis;
let hasErrors = false;

// Проверяем каждое правило
for (const rule of validationRules) {
  if (rule.check(analysis)) {
    errors.push({
      rule: rule.name,
      error: rule.error
    });
    
    hasErrors = true;
    
    // Пытаемся исправить
    fixedText = rule.fix(fixedText);
  }
}

// ═══════════════════════════════════════════════════════════════════
// ВОЗВРАЩАЕМ РЕЗУЛЬТАТ
// ═══════════════════════════════════════════════════════════════════

if (hasErrors) {
  console.log('⚠️ ОБНАРУЖЕНЫ ОШИБКИ В АНАЛИЗЕ:');
  errors.forEach(err => {
    console.log(`- ${err.rule}: ${err.error}`);
  });
  console.log('✅ Ошибки автоматически исправлены');
  
  return [{
    json: {
      content: fixedText,
      had_errors: true,
      errors: errors,
      original_content: analysis
    }
  }];
}

console.log('✅ Анализ прошёл валидацию без ошибок');

return [{
  json: {
    content: analysis,
    had_errors: false,
    errors: []
  }
}];
